test('guarda y edita una dirección que persiste al recargar', async ({ page, request }) => {
  const customer = await createCustomer(request)
  await login(page, customer.email)
  await saveAddress(page)
  await page.getByRole('button', { name: 'Editar dirección en Calle de prueba 12', exact: true }).click()
  await page.getByLabel('Calle y número', { exact: true }).fill('Calle de prueba 24')
  await page.getByRole('button', { name: 'Guardar dirección', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Dirección actualizada.' })).toBeVisible()
  await page.reload()
  const addresses = page.getByRole('list', { name: 'Direcciones guardadas' })
  await expect(addresses).toContainText('Calle de prueba 24')
  await expect(addresses).not.toContainText('Calle de prueba 12')
})

test('guarda y quita una prenda de favoritos desde Mi cuenta', async ({ page, request }) => {
  const customer = await createCustomer(request)
  await login(page, customer.email)
  const shirt = await product(request)
  await page.goto(`/shop/${shirt.id}`)
  await page.getByRole('button', { name: /Guardar en favoritos/ }).click()
  await expect(page.getByRole('button', { name: /Quitar de favoritos/ })).toHaveAttribute('aria-pressed', 'true')
  await page.goto('/account#favorites')
  const favorites = page.locator('#favorites')
  await expect(favorites).toContainText('Camisa E2E')
  await favorites.getByRole('button', { name: /Quitar de favoritos/ }).click()
  await expect(favorites).toContainText('Todavía no has guardado prendas en favoritos.')
  await page.reload()
  await expect(favorites).toContainText('Todavía no has guardado prendas en favoritos.')
})

test('filtra por categoría y no permite elegir una talla agotada', async ({ page }) => {
  await page.goto('/shop')
  await page.getByLabel('Filtrar por categoría', { exact: true }).selectOption('Gorras')
  await expect(page.getByRole('heading', { name: 'Gorra E2E', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Camisa E2E', exact: true })).toHaveCount(0)
  const shirt = await product(page.request)
  await page.goto(`/shop/${shirt.id}`)
  await expect(page.getByRole('button', { name: 'L: agotada', exact: true })).toBeDisabled()
  await expect(page.getByTestId('add-to-cart')).toBeDisabled()
})

test('cesta: añade, cambia cantidad, comprueba disponibilidad y elimina', async ({ page, request }) => {
  const customer = await createCustomer(request)
  await login(page, customer.email)
  await addShirt(page)
  await page.goto('/cart')
  await page.getByRole('button', { name: 'Aumentar cantidad de Camisa E2E, talla S', exact: true }).click()
  await expect(page.getByRole('group', { name: 'Cantidad de Camisa E2E, talla S', exact: true })).toContainText('2')
  await page.reload()
  await expect(page.getByRole('group', { name: 'Cantidad de Camisa E2E, talla S', exact: true })).toContainText('2')
  await page.getByTestId('validate-cart').click()
  await expect(page.getByTestId('cart-validation-success')).toBeVisible()
  await expect(page.getByRole('link', { name: 'Continuar con la compra', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Eliminar Camisa E2E, talla S', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Tu carrito está vacío.' })).toBeVisible()
})

test('checkout exige dirección y comprueba la compra sin crear ni cobrar un pedido', async ({ page, request }) => {
  const customer = await createCustomer(request)
  await login(page, customer.email)
  await addShirt(page)
  await page.goto('/checkout')
  await expect(page.getByTestId('validate-checkout')).toBeDisabled()
  await page.getByRole('link', { name: 'Añadir una dirección', exact: true }).click()
  await saveAddress(page)
  await page.goto('/checkout')
  await page.getByRole('radio').check()
  await page.getByTestId('validate-checkout').click()
  await expect(page.getByRole('status').filter({ hasText: 'Todavía no se ha creado ni cobrado ningún pedido.' })).toBeVisible()
  await expect(page.getByTestId('pay-checkout')).toBeEnabled()
})

