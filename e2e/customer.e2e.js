test('la cesta queda separada al cambiar de cuenta y vuelve al iniciar sesión', async ({ page, request }) => {
  test.setTimeout(120000)
  const first = await createCustomer(request)
  const second = await createCustomer(request)
  await login(page, first.email)
  await addShirt(page)
  await page.goto('/account')
  await page.getByRole('button', { name: 'Cerrar sesión', exact: true }).click()
  await login(page, second.email)
  await page.goto('/cart')
  await expect(page.getByRole('status').filter({ hasText: 'Tu carrito está vacío.' })).toBeVisible()
  await page.goto('/account')
  await page.getByRole('button', { name: 'Cerrar sesión', exact: true }).click()
  await login(page, first.email)
  await page.goto('/cart')
  await expect(page.getByRole('heading', { name: 'Camisa E2E', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Camisa E2E', exact: true })).toBeVisible()
})
