import { randomUUID } from 'node:crypto'
import { test, expect, PASSWORD, createCustomer, login, product, addShirt, saveAddress } from './helpers.js'

test('registro, sesión persistente y cierre de sesión', async ({ page }) => {
  const email = `e2e-${randomUUID()}@example.test`
  await page.goto('/register')
  await page.getByLabel('Nombre', { exact: true }).fill('Registro E2E')
  await page.getByLabel('Correo electrónico', { exact: true }).fill(email)
  await page.getByLabel('Contraseña', { exact: true }).fill(PASSWORD)
  await page.getByLabel('Repetir contraseña', { exact: true }).fill(PASSWORD)
  await page.getByRole('button', { name: 'Crear cuenta', exact: true }).click()
  await expect(page).toHaveURL(/\/login$/)
  await login(page, email)
  await expect(page.locator('main')).toContainText(email)
  await page.reload()
  await expect(page.locator('main')).toContainText(email)
  await page.getByRole('button', { name: 'Cerrar sesión', exact: true }).click()
  await page.goto('/account')
  await expect(page).toHaveURL(/\/login$/)
})

